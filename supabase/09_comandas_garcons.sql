-- Gestor de comandas e garçons (executar no SQL Editor do Supabase de teste)
create table if not exists public.garcons (
  id bigint generated by default as identity primary key,
  empresa_id bigint not null references public.empresas(id) on delete cascade,
  nome text not null check (length(trim(nome)) between 2 and 120),
  telefone text,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists garcons_empresa_idx on public.garcons(empresa_id);

create table if not exists public.comandas (
  id bigint generated by default as identity primary key,
  empresa_id bigint not null references public.empresas(id) on delete cascade,
  mesa text not null check (length(trim(mesa)) between 1 and 80),
  garcom_id bigint references public.garcons(id) on delete set null,
  status text not null default 'aberta' check (status in ('aberta','fechada')),
  observacoes text,
  created_at timestamptz not null default now(),
  closed_at timestamptz
);
create index if not exists comandas_empresa_status_idx on public.comandas(empresa_id,status,created_at desc);

create table if not exists public.itens_comanda (
  id bigint generated by default as identity primary key,
  comanda_id bigint not null references public.comandas(id) on delete cascade,
  produto_id bigint references public.produtos(id) on delete set null,
  produto_nome text not null,
  quantidade integer not null check (quantidade between 1 and 99),
  preco_unitario numeric(10,2) not null check (preco_unitario >= 0),
  created_at timestamptz not null default now()
);
create index if not exists itens_comanda_comanda_idx on public.itens_comanda(comanda_id);

alter table public.garcons enable row level security;
alter table public.comandas enable row level security;
alter table public.itens_comanda enable row level security;

drop policy if exists garcons_owner_all on public.garcons;
create policy garcons_owner_all on public.garcons for all to authenticated
using (exists (select 1 from public.empresas e where e.id = empresa_id and e.dono_id = auth.uid()))
with check (exists (select 1 from public.empresas e where e.id = empresa_id and e.dono_id = auth.uid()));

drop policy if exists comandas_owner_all on public.comandas;
create policy comandas_owner_all on public.comandas for all to authenticated
using (exists (select 1 from public.empresas e where e.id = empresa_id and e.dono_id = auth.uid()))
with check (
  exists (select 1 from public.empresas e where e.id = empresa_id and e.dono_id = auth.uid())
  and (garcom_id is null or exists (select 1 from public.garcons g where g.id = garcom_id and g.empresa_id = empresa_id))
);

drop policy if exists itens_comanda_owner_all on public.itens_comanda;
create policy itens_comanda_owner_all on public.itens_comanda for all to authenticated
using (exists (select 1 from public.comandas c join public.empresas e on e.id = c.empresa_id where c.id = comanda_id and e.dono_id = auth.uid()))
with check (exists (select 1 from public.comandas c join public.empresas e on e.id = c.empresa_id where c.id = comanda_id and e.dono_id = auth.uid()));
