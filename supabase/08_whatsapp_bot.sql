-- Execute no SQL Editor do projeto Supabase de TESTE antes de salvar configurações no painel.

create table if not exists public.whatsapp_bot_config (
  id bigint generated by default as identity primary key,
  empresa_id integer not null unique references public.empresas(id) on delete cascade,
  config jsonb not null default '{}'::jsonb,
  meta_phone_number_id text,
  connection_note text,
  atualizado_por uuid references auth.users(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

alter table public.whatsapp_bot_config enable row level security;

drop policy if exists dono_whatsapp_bot_config_all on public.whatsapp_bot_config;
create policy dono_whatsapp_bot_config_all
on public.whatsapp_bot_config
for all
to authenticated
using (
  exists (
    select 1 from public.empresas e
    where e.id = empresa_id and e.dono_id = auth.uid()
  )
)
with check (
  exists (
    select 1 from public.empresas e
    where e.id = empresa_id and e.dono_id = auth.uid()
  )
);

grant select, insert, update, delete on public.whatsapp_bot_config to authenticated;
